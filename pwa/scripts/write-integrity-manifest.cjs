const crypto = require('node:crypto')
const fs = require('node:fs')
const path = require('node:path')

const root = path.resolve(__dirname, '..')
const buildDir = process.env.SAT20_PWA_BUILD_DIR
if (buildDir && !path.isAbsolute(buildDir)) {
  throw new Error('SAT20_PWA_BUILD_DIR must be an absolute private directory')
}
const outputRoot = buildDir || root
const versionPath = path.join(outputRoot, 'public', 'version.json')
const publicManifestPath = path.join(outputRoot, 'public', 'integrity-manifest.json')
const generatedModulePath = path.join(outputRoot, 'generated', 'wasm-integrity.ts')

const assets = [
  {
    role: 'go-runtime',
    path: 'wasm/wasm_exec.js',
    mimeTypes: ['text/javascript', 'application/javascript'],
  },
  {
    role: 'wallet-wasm',
    path: 'wasm/sat20wallet.wasm',
    mimeTypes: ['application/wasm'],
  },
]

const version = JSON.parse(fs.readFileSync(versionPath, 'utf8'))
if (!version.version || !version.buildId) {
  throw new Error('public/version.json must contain version and buildId before generating integrity metadata')
}

const manifest = {
  schemaVersion: 1,
  releaseId: `${version.version}-${version.buildId}`,
  assets: assets.map((asset) => {
    const bytes = fs.readFileSync(path.join(outputRoot, 'public', asset.path))
    return {
      ...asset,
      size: bytes.length,
      sha256: crypto.createHash('sha256').update(bytes).digest('hex'),
    }
  }),
}

const json = `${JSON.stringify(manifest, null, 2)}\n`
fs.mkdirSync(path.dirname(generatedModulePath), { recursive: true })
fs.writeFileSync(publicManifestPath, json, { flag: buildDir ? 'wx' : 'w' })
fs.writeFileSync(
  generatedModulePath,
  `// Generated by scripts/write-integrity-manifest.cjs. Do not edit by hand.\n` +
    `export const WASM_INTEGRITY_MANIFEST = ${JSON.stringify(manifest, null, 2)} as const\n`,
  { flag: buildDir ? 'wx' : 'w' }
)

console.log(`Wrote integrity metadata for release ${manifest.releaseId}`)
